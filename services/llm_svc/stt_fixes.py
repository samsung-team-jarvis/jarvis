"""STT 오인식 사전 (STT-10): 파서(·LLM)에 넣기 전에 자주 틀리는 받아쓰기를 고친다.

근거는 사람 음성 녹음의 **val 화자**에서만 찾는다
(test 화자를 보고 고치지 않는다 — experiment 원칙 2).
stt/text에는 원문이 그대로 남고, 고친 문장은 llm/function_call의 raw_text로 남는다.
"""

from __future__ import annotations

import re

# (틀린 표현, 고친 표현) — 위에서부터 차례로 바꾼다 (긴 것 먼저).
# 출처: spk01 val 40문장, MacBook 마이크 30cm 이내, 2026-10-02 (#61)
FIXES: tuple[tuple[str, str], ...] = (
    ("타임머", "타이머"),  # "타이머 취소해줘" → "타임머 취소해줘" (2건)
    ("세개", "세게"),  # "2번 화구 세게" → "이번화구 세개"
    ("세 개 해", "세게 해"),  # 띄어 쓴 꼴 — 합성 음성 리허설(#128). "세 개"만은 그대로
    ("약하 게", "약하게"),  # 띄어 쓴 꼴 — 합성 음성(#128)·보드 리허설(#166)에서 반복
    ("결 해", "결제해"),  # "결제해 줘"의 "제"를 놓침 — 합성 음성 리허설(#128, 11-23), LLM은 CONFIRM
    ("번구", "번 화구"),  # "1번 화구" → "일 번구"
    # 보드 USB 마이크 실사용 (2026-11-24, #182): "1번 허곡 해죠", "1번 허국 해줘", "1번 화국 해줘"
    ("허곡", "화구"),
    ("허국", "화구"),
    ("화국", "화구"),
    ("화곡", "화구"),  # "1 번 화곡해줘" (같은 시연)
    ("젖든", "전등"),  # "자비스 젖든 켜 줘" → LLM 대상 모름 (2026-11-25, #182)
    ("젠등", "전등"),  # "자비스 젠등 꺼줘" (같은 시연)
    ("일본 번", "일번"),  # "1번 화구" → "일본 번 화국"
    ("일본", "1번"),
)


# 숫자 + 번 + "하고" + 켜/꺼/세기 → "번 화구". 보드 핀마이크 실사용에서 "1번 화구 켜줘"가
# "일본하고 켜줘"(→ "1번하고 켜줘")로 3번 나왔다 (2026-11-17, #STT-14). 숫자 바로 뒤일 때만 바꾼다.
_BURNER_HAGO = re.compile(r"(\d)\s*번\s*하고(?=\s*(?:켜|꺼|끄|세|약|중|강))")


# "튀김 켜 줘"처럼 튀김기를 줄여 말함 (보드 실사용 2026-11-17, #STT-14). 켜기·끄기·세기 앞일 때만.
# "튀김이 켜죠"(→ LLM 상태 확인으로 읽음, 보드 USB 마이크 2026-11-25, #182)도 같은 꼴로 본다.
_FRYER_SHORT = re.compile(r"튀김이?(?!기)(?=\s*(?:켜|꺼|끄|틀|세|약|중|강))")


# "화구 켜"의 '켜'가 앞 글자에 붙어 '해'·'회'로 들린다: "2번 화국 해죠", "1 번 화곡해줘",
# "1번 화국회죠" (보드 USB 마이크 2026-11-24·25, #182). "화구 해 줘"는 뜻이 없는 말이라 켜기로 본다.
_BURNER_HAE = re.compile(r"화구\s*(?:해|회)(?=\s*(?:줘|죠|주|$|[.?!]))")

# 장치 이름 바로 뒤의 동사 오인식 (같은 시연): "튀김기거죠"(꺼죠), "후드 캐죠"(켜죠).
# 장치 이름 뒤에서 줘·죠·주로 끝날 때만 바꾼다
_DEVICE = r"(튀김기|후드|환풍기|화구|버너|전등|조명|에어컨|선풍기|음악)"
_DEVICE_GEO = re.compile(rf"{_DEVICE}\s*거(?=\s*(?:줘|죠|주))")
_DEVICE_KAE = re.compile(rf"{_DEVICE}\s*캐(?=\s*(?:줘|죠|주))")

# "1번 버너"가 "1번 번호"로 나온다 (같은 시연, 4건). 숫자 + 번 바로 뒤의 "번호"만 버너로 본다.
_BURNER_BEONHO = re.compile(r"(?<![가-힣])(\d|일|이|입)\s*번\s*번호")


def normalize(text: str) -> str:
    for wrong, right in FIXES:
        text = text.replace(wrong, right)
    text = _FRYER_SHORT.sub("튀김기", text)
    text = _BURNER_HAE.sub("화구 켜", text)
    text = _DEVICE_GEO.sub(r"\1 꺼", text)
    text = _DEVICE_KAE.sub(r"\1 켜", text)
    text = _BURNER_BEONHO.sub(r"\1번 버너", text)
    return _BURNER_HAGO.sub(r"\1번 화구", text)


# 한자어 숫자 + 단위 → 아라비아 숫자. 서비스 입력(command_text)에만 — 학습 데이터 생성엔 안 쓴다.
# 받아쓰기는 "1번"을 "일 번", "2번"을 "입 번", "10분"을 "십 분"으로 내고, LLM은 이런 꼴에서 틀렸다
# ("일 번 화구" → 2번 화구, "입 분" → 8분). 근거: spk01 val을 서비스 경로로 받아쓴 결과 (#130)
_DIGIT = {"일": 1, "이": 2, "입": 2, "삼": 3, "사": 4, "오": 5}
_DIGIT |= {"육": 6, "륙": 6, "칠": 7, "팔": 8, "구": 9}
_NUM = r"(?:[이입삼사오육륙칠팔구]?십[일이삼사오육칠팔구]?|[일이입삼사오육륙칠팔구])"
# 번은 장치 앞에서만 ("이번에"처럼 숫자가 아닌 말이 많다), 단은 "으로"·"계" 앞이나 끝에서만
# ("일단 후드 켜"의 일단은 세기가 아니다). 분·초는 뒤에 한글이 바로 붙지 않을 때
_COUNTED = re.compile(
    rf"(?<![가-힣])({_NUM})\s*(?:(번)(?=\s*(?:째|화구|불|버너|구))"
    rf"|(분|초)(?![가-힣])|(단)(?=으로|계|\s*[.,?!]|\s*$))"
)
_DIGIT_SPACE = re.compile(r"(\d)\s+(번|분|초|단)")  # "1 번" → "1번"


def _value(word: str) -> int:
    if "십" not in word:
        return _DIGIT[word]
    tens, _, ones = word.partition("십")
    return (_DIGIT[tens] if tens else 1) * 10 + (_DIGIT[ones] if ones else 0)


def numerals(text: str) -> str:
    """ "일 번 화구" → "1번 화구", "입 분" → "2분", "삼십 초" → "30초", "1 번" → "1번"."""

    def digits(m: re.Match[str]) -> str:
        return str(_value(m.group(1))) + (m.group(2) or m.group(3) or m.group(4))

    text = _COUNTED.sub(digits, text)
    return _DIGIT_SPACE.sub(r"\1\2", text)
